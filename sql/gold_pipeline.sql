-- Run the setup, then load the silver exports into STAGING before continuing.
CREATE DATABASE IF NOT EXISTS CLAIMS_PIPELINE;
CREATE SCHEMA IF NOT EXISTS CLAIMS_PIPELINE.STAGING;
CREATE SCHEMA IF NOT EXISTS CLAIMS_PIPELINE.GOLD;

CREATE TABLE IF NOT EXISTS CLAIMS_PIPELINE.GOLD.CLAIMS
LIKE CLAIMS_PIPELINE.STAGING.SILVER_CLAIMS;

MERGE INTO CLAIMS_PIPELINE.GOLD.CLAIMS AS target
USING CLAIMS_PIPELINE.STAGING.SILVER_CLAIMS AS source
ON target.CLAIM_ID = source.CLAIM_ID
WHEN MATCHED THEN UPDATE ALL BY NAME
WHEN NOT MATCHED THEN INSERT ALL BY NAME;

CREATE TABLE IF NOT EXISTS CLAIMS_PIPELINE.GOLD.TRANSACTIONS
LIKE CLAIMS_PIPELINE.STAGING.SILVER_TRANSACTIONS;

MERGE INTO CLAIMS_PIPELINE.GOLD.TRANSACTIONS AS target
USING (
    SELECT t.*
    FROM CLAIMS_PIPELINE.STAGING.SILVER_TRANSACTIONS AS t
    INNER JOIN CLAIMS_PIPELINE.GOLD.CLAIMS AS c ON t.CLAIM_ID = c.CLAIM_ID
) AS source
ON target.TRANSACTION_ID = source.TRANSACTION_ID
WHEN MATCHED THEN UPDATE ALL BY NAME
WHEN NOT MATCHED THEN INSERT ALL BY NAME;

SELECT 'CLAIMS' AS DATASET, COUNT(*) AS ROW_COUNT
FROM CLAIMS_PIPELINE.GOLD.CLAIMS
UNION ALL
SELECT 'TRANSACTIONS', COUNT(*)
FROM CLAIMS_PIPELINE.GOLD.TRANSACTIONS;

SELECT
    c.BATCH_ID AS CLAIM_BATCH_WEEK,
    COUNT(DISTINCT c.CLAIM_ID) AS CLAIM_COUNT,
    SUM(CASE
        WHEN t.TRANSACTION_TYPE = 'PAYMENT' THEN COALESCE(t.PAYMENT_AMOUNT, 0)
        ELSE 0
    END) AS TOTAL_PAID
FROM CLAIMS_PIPELINE.GOLD.CLAIMS AS c
LEFT JOIN CLAIMS_PIPELINE.GOLD.TRANSACTIONS AS t ON c.CLAIM_ID = t.CLAIM_ID
GROUP BY c.BATCH_ID
ORDER BY c.BATCH_ID DESC;
