-- Run as an account administrator after the staging and gold tables exist.
-- Replace COMPUTE_WH below if the pipeline uses a different warehouse.
CREATE ROLE IF NOT EXISTS CLAIMS_PIPELINE_LOADER;
CREATE ROLE IF NOT EXISTS CLAIMS_PIPELINE_REPORTER;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE CLAIMS_PIPELINE_REPORTER;
GRANT USAGE ON DATABASE CLAIMS_PIPELINE TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT USAGE ON DATABASE CLAIMS_PIPELINE TO ROLE CLAIMS_PIPELINE_REPORTER;

GRANT USAGE ON SCHEMA CLAIMS_PIPELINE.STAGING TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT USAGE ON SCHEMA CLAIMS_PIPELINE.GOLD TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT USAGE ON SCHEMA CLAIMS_PIPELINE.GOLD TO ROLE CLAIMS_PIPELINE_REPORTER;

GRANT SELECT, INSERT ON TABLE CLAIMS_PIPELINE.STAGING.SILVER_CLAIMS
    TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT SELECT, INSERT ON TABLE CLAIMS_PIPELINE.STAGING.SILVER_TRANSACTIONS
    TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT SELECT, INSERT, UPDATE ON TABLE CLAIMS_PIPELINE.GOLD.CLAIMS
    TO ROLE CLAIMS_PIPELINE_LOADER;
GRANT SELECT, INSERT, UPDATE ON TABLE CLAIMS_PIPELINE.GOLD.TRANSACTIONS
    TO ROLE CLAIMS_PIPELINE_LOADER;

GRANT SELECT ON TABLE CLAIMS_PIPELINE.GOLD.CLAIMS TO ROLE CLAIMS_PIPELINE_REPORTER;
GRANT SELECT ON TABLE CLAIMS_PIPELINE.GOLD.TRANSACTIONS TO ROLE CLAIMS_PIPELINE_REPORTER;

SHOW GRANTS TO ROLE CLAIMS_PIPELINE_LOADER;
SHOW GRANTS TO ROLE CLAIMS_PIPELINE_REPORTER;

-- Run separately as an account administrator for loading and merge audit.
SELECT query_id, start_time, user_name, role_name, query_tag, query_type,
       execution_status, rows_inserted, rows_updated
FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
WHERE role_name = 'CLAIMS_PIPELINE_LOADER'
  AND STARTSWITH(query_tag, 'claims_pipeline_load:')
  AND start_time >= DATEADD('day', -7, CURRENT_TIMESTAMP())
ORDER BY start_time DESC;
